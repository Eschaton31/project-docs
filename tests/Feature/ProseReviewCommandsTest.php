<?php

namespace Tests\Feature;

use App\Ai\Agents\ProseReviewer;
use App\Models\Document;
use App\Models\ProseReview;
use App\Models\ProseSuggestion;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\File;
use Tests\TestCase;

class ProseReviewCommandsTest extends TestCase
{
    use RefreshDatabase;

    private string $workDir;

    private User $admin;

    private Document $document;

    private array $blocks;

    protected function setUp(): void
    {
        parent::setUp();

        $this->workDir = sys_get_temp_dir().'/prose-reviews-'.uniqid();
        config(['ai-review.work_dir' => $this->workDir]);
        ProseReviewer::fake()->preventStrayPrompts();

        $this->actingAs($this->admin = User::factory()->admin()->create());
        $this->document = Document::where('slug', $this->postJson('/api/documents', ['title' => 'Setup Guide'])->json('document.slug'))->firstOrFail();
        // B1 SETUP > B2 Paragraph > B3 RichText; B4 USAGE > B5 Paragraph > B6 RichText
        $this->blocks = $this->postJson("/api/documents/{$this->document->slug}/blocks/tree", ['blocks' => [
            ['type' => 'PrimaryTopic', 'props' => ['title' => 'SETUP'], 'children' => [
                ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'In order to install it, you need PHP, a database and Chrome.']]]],
            ]],
            ['type' => 'PrimaryTopic', 'props' => ['title' => 'USAGE'], 'children' => [
                ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'The report is generated by the user.']]]],
            ]],
        ]])->json('blocks');
    }

    protected function tearDown(): void
    {
        File::deleteDirectory($this->workDir);

        parent::tearDown();
    }

    public function test_export_saves_what_is_reviewed_and_writes_the_instructions_and_prompts(): void
    {
        $this->artisan('prose-review:export', ['document' => $this->document->slug, '--user' => $this->admin->email])
            ->expectsOutputToContain('Review: ')
            ->expectsOutputToContain('php artisan prose-review:import')
            ->assertSuccessful();

        $review = ProseReview::query()->sole();
        $this->assertSame([ProseReview::AWAITING, ProseReview::CLAUDE_CODE, $this->admin->id], [$review->status, $review->model, $review->requested_by]);
        $this->assertSame($this->document->fresh()->seq, $review->document_seq);
        $this->assertSame([['B1', 'B2', 'B3', 'B4', 'B5', 'B6']], $review->snapshot['chunks']);

        $dir = str_replace('\\', '/', "{$this->workDir}/{$review->id}");
        $this->assertStringContainsString('# How to answer', File::get("{$dir}/instructions.md"));
        $this->assertStringContainsString('Laravel documentation', File::get("{$dir}/instructions.md"));
        $chunk = File::get("{$dir}/chunk-1.md");
        $this->assertStringContainsString("Write your answer to: {$dir}/chunk-1.json", str_replace('\\', '/', $chunk));
        $this->assertStringContainsString('«In order to install it, you need PHP, a database and Chrome.»', $chunk);
        // nothing is sent anywhere
        ProseReviewer::assertNeverPrompted();
    }

    public function test_export_can_review_one_topic_for_wording_only(): void
    {
        $this->artisan('prose-review:export', ['document' => $this->document->slug, '--block' => $this->blocks[1]['id'], '--kinds' => 'text'])
            ->assertSuccessful();

        $review = ProseReview::query()->sole();
        $this->assertSame(['text'], $review->kinds);
        $chunk = File::get("{$this->workDir}/{$review->id}/chunk-1.md");
        $this->assertStringContainsString('«The report is generated by the user.»', $chunk);
        $this->assertStringNotContainsString('In order to install it', $chunk);
        $this->assertStringContainsString('Return an empty "restructure" list', $chunk);
    }

    public function test_export_refuses_bad_input(): void
    {
        $this->artisan('prose-review:export', ['document' => 'nope'])->assertFailed();
        $this->artisan('prose-review:export', ['document' => $this->document->slug, '--kinds' => 'tone'])->assertFailed();
        $this->artisan('prose-review:export', ['document' => $this->document->slug, '--block' => '01234567-89ab-cdef-0123-456789abcdef'])->assertFailed();
        $this->artisan('prose-review:export', ['document' => $this->document->slug, '--user' => User::factory()->create()->email])->assertFailed();

        $this->assertSame(0, ProseReview::query()->count());
    }

    public function test_import_saves_the_valid_suggestions_and_reports_the_rest(): void
    {
        $review = $this->export();
        $this->answer($review, 1, [
            'text' => [
                $this->text('S2', 'In order to install it', 'To install it', 'hedging'),
                $this->text('S4', 'The report is generated by the user.', 'You generate the report.', 'passive'),
                $this->text('S2', 'not in the text', 'anything', 'clarity'),
            ],
            'restructure' => [[
                'blocks' => ['B2'],
                'replacement_json' => json_encode([
                    ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'To install it, you need:']]]],
                    ['type' => 'BulletList', 'props' => ['list' => ['PHP', 'A database', 'Chrome']]],
                ]),
                'rule' => 'list', 'rationale' => 'Parallel items read better as a list.', 'severity' => 'major',
            ]],
        ]);

        $this->artisan('prose-review:import', ['review' => $review->id])
            ->expectsOutputToContain('Saved 3 suggestions')
            ->expectsOutputToContain('original not found once in the segment')
            ->assertSuccessful();

        $review->refresh();
        $this->assertSame(ProseReview::DONE, $review->status);
        $this->assertNull($review->snapshot);
        $this->assertSame(['hedging', 'passive', 'list'], $review->suggestions()->orderBy('id')->pluck('rule')->all());
        $this->assertSame([ProseSuggestion::PENDING], $review->suggestions()->distinct()->pluck('status')->all());
    }

    public function test_answers_are_read_against_the_exported_text_even_after_edits(): void
    {
        $review = $this->export();
        // someone edits the second topic between export and import
        $usage = $this->blocks[1]['children'][0]['children'][0];
        $this->patchJson("/api/blocks/{$usage['id']}", ['version' => 1, 'props' => ['html' => 'Rewritten by hand.']])->assertOk();
        $this->answer($review, 1, ['text' => [$this->text('S4', 'The report is generated by the user.', 'You generate the report.', 'passive')], 'restructure' => []]);

        $this->artisan('prose-review:import', ['review' => $review->id])->assertSuccessful();

        // saved against the exported text; accepting it will find the text changed and mark it stale
        $suggestion = $review->suggestions()->sole();
        $this->assertSame([$usage['id'] => 1], $suggestion->block_versions);
        $this->postJson("/api/suggestions/{$suggestion->id}/accept")->assertConflict();
    }

    public function test_import_needs_every_answer_and_changes_nothing_until_then(): void
    {
        config(['ai-review.max_chars_per_chunk' => 70]);
        $review = $this->export();
        $this->assertCount(2, $review->snapshot['chunks']);
        $this->answer($review, 1, ['text' => [], 'restructure' => []]);

        $this->artisan('prose-review:import', ['review' => $review->id])
            ->expectsOutputToContain('chunk-2.json: missing')
            ->assertFailed();
        $this->assertSame(ProseReview::AWAITING, $review->fresh()->status);

        File::put("{$this->workDir}/{$review->id}/chunk-2.json", '```json {"text": []} ```');
        $this->artisan('prose-review:import', ['review' => $review->id])->expectsOutputToContain('not a JSON object')->assertFailed();

        $this->answer($review, 2, ['text' => [], 'restructure' => []]);
        $this->artisan('prose-review:import', ['review' => $review->id])->expectsOutputToContain('Saved 0 suggestions')->assertSuccessful();
        $this->artisan('prose-review:import', ['review' => $review->id])->assertFailed();
    }

    private function export(): ProseReview
    {
        $this->artisan('prose-review:export', ['document' => $this->document->slug])->assertSuccessful();

        return ProseReview::query()->latest('id')->firstOrFail();
    }

    private function answer(ProseReview $review, int $chunk, array $output): void
    {
        File::put("{$this->workDir}/{$review->id}/chunk-{$chunk}.json", json_encode($output));
    }

    private function text(string $segment, string $original, string $suggested, string $rule): array
    {
        return ['segment' => $segment, 'original' => $original, 'suggested' => $suggested, 'rule' => $rule, 'rationale' => 'Style guide.', 'severity' => 'minor'];
    }
}
