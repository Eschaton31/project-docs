<?php

namespace Tests\Feature;

use App\Ai\Agents\ProseReviewer;
use App\Jobs\ReviewProse;
use App\Models\Document;
use App\Models\ProseReview;
use App\Models\ProseSuggestion;
use App\Models\User;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Laravel\Ai\Prompts\AgentPrompt;
use RuntimeException;
use Tests\TestCase;

class ProseReviewJobTest extends TestCase
{
    use RefreshDatabase;

    private User $admin;

    private Document $document;

    /** top-level blocks as the insert-tree endpoint returned them */
    private array $blocks;

    protected function setUp(): void
    {
        parent::setUp();

        $this->actingAs($this->admin = User::factory()->admin()->create());
        $this->document = Document::where('slug', $this->postJson('/api/documents', ['title' => 'Setup Guide'])->json('document.slug'))->firstOrFail();

        // B1 SETUP > B2 Paragraph > B3 RichText, B4 CodeBlock; B5 USAGE > B6 Paragraph > B7 RichText
        $this->blocks = $this->postJson("/api/documents/{$this->document->slug}/blocks/tree", ['blocks' => [
            ['type' => 'PrimaryTopic', 'props' => ['title' => 'SETUP'], 'children' => [
                ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'In order to install it, you need PHP, a database and Chrome.']]]],
                ['type' => 'CodeBlock', 'props' => ['lang' => 'bash', 'code' => 'composer install']],
            ]],
            ['type' => 'PrimaryTopic', 'props' => ['title' => 'USAGE'], 'children' => [
                ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'The report is generated by the user.']]]],
            ]],
        ]])->assertCreated()->json('blocks');
    }

    public function test_valid_suggestions_are_saved_and_invalid_ones_dropped(): void
    {
        ProseReviewer::fake([[
            'text' => [
                $this->text('S2', 'In order to install it', 'To install it', 'hedging'),
                $this->text('S4', 'The report is generated by the user.', 'You generate the report.', 'passive'),
                $this->text('S2', 'not in the text', 'anything', 'clarity'),
            ],
            'restructure' => [[
                'blocks' => ['B2'],
                'replacement_json' => json_encode([
                    ['type' => 'Paragraph', 'children' => [['type' => 'RichText', 'props' => ['html' => 'To install it, you need:']]]],
                    ['type' => 'BulletList', 'props' => ['list' => ['PHP', 'A database', 'Chrome']]],
                ]),
                'rule' => 'list', 'rationale' => 'Parallel items read better as a list.', 'severity' => 'major',
            ]],
        ]])->preventStrayPrompts();

        $review = $this->review();
        ReviewProse::dispatch($review);

        $review->refresh();
        $this->assertSame(ProseReview::DONE, $review->status);
        $this->assertSame($this->document->fresh()->seq, $review->document_seq);
        $suggestions = $review->suggestions()->orderBy('id')->get();
        $this->assertSame(['hedging', 'passive', 'list'], $suggestions->pluck('rule')->all());
        $this->assertSame([ProseSuggestion::PENDING], $suggestions->pluck('status')->unique()->values()->all());
        $this->assertSame([$this->blocks[0]['children'][0]['children'][0]['id']], $suggestions[0]->block_ids);
        $this->assertSame([$this->blocks[0]['children'][0]['id']], $suggestions[2]->block_ids);
        $this->assertSame($this->blocks[0]['id'], $suggestions[2]->parent_id);
    }

    public function test_the_prompt_carries_the_outline_and_the_scope_text_with_the_chosen_model(): void
    {
        ProseReviewer::fake([['text' => [], 'restructure' => []]]);

        ReviewProse::dispatch($this->review(['model' => 'opus', 'scope_block_id' => $this->blocks[1]['id'], 'kinds' => ['text']]));

        ProseReviewer::assertPrompted(fn (AgentPrompt $prompt) => $prompt->model === 'claude-opus-5-5'
            && $prompt->contains('Suggestion kinds requested: text.')
            && $prompt->contains('«The report is generated by the user.»')
            && ! $prompt->contains('In order to install it'));
        ProseReviewer::assertPromptedTimes(1);
    }

    public function test_a_large_document_is_reviewed_in_several_prompts(): void
    {
        config(['ai-review.max_chars_per_chunk' => 70]);
        ProseReviewer::fake([
            ['text' => [$this->text('S2', 'In order to install it', 'To install it', 'hedging')], 'restructure' => []],
            ['text' => [$this->text('S4', 'The report is generated by the user.', 'You generate the report.', 'passive')], 'restructure' => []],
        ])->preventStrayPrompts();

        $review = $this->review();
        ReviewProse::dispatch($review);

        ProseReviewer::assertPromptedTimes(2);
        $this->assertSame(2, $review->suggestions()->count());
        $this->assertSame(ProseReview::DONE, $review->fresh()->status);
    }

    public function test_a_failed_model_call_fails_the_review(): void
    {
        ProseReviewer::fake(fn () => throw new RuntimeException('Overloaded.'));

        $review = $this->review();
        try {
            ReviewProse::dispatch($review);
        } catch (RuntimeException) {
            // the sync queue rethrows after failed() ran
        }

        $this->assertSame(ProseReview::FAILED, $review->fresh()->status);
        $this->assertSame('Overloaded.', $review->fresh()->error);
        $this->assertSame(0, $review->suggestions()->count());
    }

    private function review(array $attributes = []): ProseReview
    {
        return $this->document->proseReviews()->create([
            'requested_by' => $this->admin->id,
            'model' => 'sonnet',
            'kinds' => ['text', 'restructure'],
            'status' => ProseReview::QUEUED,
            ...$attributes,
        ]);
    }

    private function text(string $segment, string $original, string $suggested, string $rule): array
    {
        return ['segment' => $segment, 'original' => $original, 'suggested' => $suggested, 'rule' => $rule, 'rationale' => 'Style guide.', 'severity' => 'minor'];
    }
}
